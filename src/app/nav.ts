export function visibleNav(can: (p: string | string[]) => boolean): NavModule[] {
  return NAV.filter((m) => !m.perm || can(m.perm))
    .map((m) => ({ ...m, items: m.items.filter((i) => !i.perm || can(i.perm)) }))
    .filter((m) => m.items.length > 0)
}

export function findNavLabel(pathname: string, search = ''): { module?: string; item?: string } {
  const full = pathname + search
  for (const m of NAV) {
    const exact = m.items.find((i) => i.path === full) || m.items.find((i) => i.path === pathname)
    if (exact) return { module: m.label, item: exact.label }
  }
  return {}
}
